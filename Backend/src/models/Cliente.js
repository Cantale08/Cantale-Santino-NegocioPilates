class Cliente {
    constructor(id, nombre, apellido, email, contrasenia, telefono, dni) {
        this.id = id;
        this.nombre = nombre;
        this.apellido = apellido;
        this.email = email;
        this.contrasenia = contrasenia;
        this.telefono = telefono;
        this.dni = dni;
    }
}

export default Cliente;
