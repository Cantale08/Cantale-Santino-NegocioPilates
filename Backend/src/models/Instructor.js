class Instructor {
    constructor(id, nombre, apellido, email, contrasenia, telefono, dni, disponibilidad) {
        this.id = id;
        this.nombre = nombre;
        this.apellido = apellido;
        this.email = email;
        this.contrasenia = contrasenia;
        this.telefono = telefono;
        this.dni = dni;
        this.disponibilidad = disponibilidad;
    }
}

export default Instructor;
